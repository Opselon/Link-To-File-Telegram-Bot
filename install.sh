#!/usr/bin/env bash
# ⚡ Link → File — one-line installer
#
#   curl -fsSL https://raw.githubusercontent.com/Opselon/Link-To-File-Telegram-Bot/main/install.sh | bash
#
# Non-interactive:
#   BOT_TOKEN=123:abc ADMIN_ID=42 curl -fsSL … | bash
#
# Options (env vars): BOT_TOKEN, ADMIN_ID, INSTALL_DIR, FORCE=1, NO_START=1
# Flags: --uninstall
set -euo pipefail

REPO="Opselon/Link-To-File-Telegram-Bot"
BRANCH="main"
IMAGE="ghcr.io/opselon/link-to-file-telegram-bot"

TOKEN="${BOT_TOKEN:-}"
ADMIN="${ADMIN_ID:-}"
DIR="${INSTALL_DIR:-$HOME/link-to-file}"
FORCE="${FORCE:-0}"
NO_START="${NO_START:-0}"

BOLD=$'\033[1m'; DIM=$'\033[2m'; RED=$'\033[31m'; GREEN=$'\033[32m'
YELLOW=$'\033[33m'; CYAN=$'\033[36m'; RESET=$'\033[0m'

info() { printf '  %s\n' "$1"; }
ok()   { printf '  %s%s%s %s\n' "$GREEN" "✔" "$RESET" "$1"; }
warn() { printf '  %s%s%s %s\n' "$YELLOW" "!" "$RESET" "$1" >&2; }
die()  { printf '  %s%s%s %s\n' "$RED" "✖" "$RESET" "$1" >&2; exit 1; }
step() { printf '\n  %s%s%s\n' "$BOLD" "$1" "$RESET"; }

has() { command -v "$1" >/dev/null 2>&1; }
docker_ready() { has docker && docker info >/dev/null 2>&1; }

ask() {
  local prompt="$1" default="${2:-}" answer=""
  [ -n "$default" ] && prompt="$prompt [$default]"
  if [ -t 0 ]; then
    printf '  %s%s%s ' "$CYAN" "$prompt" "$RESET" >&2
    IFS= read -r answer || true
  fi
  printf '%s' "${answer:-$default}"
}

token_ok() { [[ "$1" =~ ^[0-9]{6,}:[A-Za-z0-9_-]{20,}$ ]]; }

prompt_credentials() {
  if [ -z "$TOKEN" ] && [ -t 0 ]; then
    step "Telegram credentials"
    info "${DIM}Create a bot with @BotFather, then paste its token.${RESET}"
    while true; do
      TOKEN="$(ask 'Bot token:')"
      [ -z "$TOKEN" ] && { warn "Token is required to start the bot."; continue; }
      token_ok "$TOKEN" && break
      warn "That doesn't look like a bot token (expected 123456:ABC…)."
    done
    if [ -z "$ADMIN" ]; then
      info "${DIM}Your numeric Telegram ID (send /id to @userinfobot).${RESET}"
      ADMIN="$(ask 'Admin user ID (optional):')"
    fi
  fi
}

write_env() {
  local file="$1"
  if [ -s "$file" ] && [ "$FORCE" != "1" ]; then
    # keep an existing config; only fill in credentials that were provided
    [ -n "$TOKEN" ] && sed -i "s|^BOT_TOKEN=.*|BOT_TOKEN=$TOKEN|" "$file"
    [ -n "$ADMIN" ] && sed -i "s|^ADMIN_ID=.*|ADMIN_ID=$ADMIN|" "$file" || true
    return
  fi
  {
    echo "# ⚡ Link → File — generated by install.sh"
    echo "BOT_TOKEN=${TOKEN}"
    echo "ADMIN_ID=${ADMIN}"
    echo
    echo "MAX_FILE_SIZE_MB=2000"
    echo "DOWNLOAD_TIMEOUT=600"
    echo "QUEUE_CONCURRENCY=3"
    echo "RATE_LIMIT_SECONDS=3"
  } > "$file"
  chmod 600 "$file"
}

install_docker() {
  mkdir -p "$DIR"
  if [ "$FORCE" = "1" ] || [ ! -f "$DIR/docker-compose.yml" ]; then
    curl -fsSL "https://raw.githubusercontent.com/$REPO/$BRANCH/docker-compose.yml" \
      -o "$DIR/docker-compose.yml" || die "could not download docker-compose.yml"
  fi
  write_env "$DIR/.env"

  if ! token_ok "$TOKEN"; then
    ok "Installed to $DIR"
    info "Open ${BOLD}$DIR/.env${RESET}, set BOT_TOKEN and ADMIN_ID, then run:"
    info "  ${BOLD}cd $DIR && docker compose up -d${RESET}"
    return 0
  fi

  step "Fetching the image"
  if ! (cd "$DIR" && docker compose pull -q); then
    warn "Image pull failed — building locally instead"
    (cd "$DIR" && docker compose build -q) || die "build failed"
  fi

  [ "$NO_START" = "1" ] && { ok "Everything is ready in $DIR (not started, NO_START=1)"; return 0; }

  step "Starting"
  (cd "$DIR" && docker compose up -d --wait) || {
    (cd "$DIR" && docker compose up -d)
    warn "Health check did not pass in time — check: cd $DIR && docker compose logs --tail=50"
  }
  ok "Container is up"
  info "Logs:   ${BOLD}cd $DIR && docker compose logs -f${RESET}"
  info "Update: ${BOLD}cd $DIR && docker compose pull && docker compose up -d${RESET}"
  info "Stop:   ${BOLD}cd $DIR && docker compose down${RESET}"
}

install_python() {
  has git || die "git is required for the Python install (apt install git)"
  mkdir -p "$(dirname "$DIR")"
  if [ ! -d "$DIR/.git" ]; then
    step "Downloading the source"
    git clone -q --depth 1 "https://github.com/$REPO.git" "$DIR" || die "git clone failed"
  elif [ "$FORCE" != "1" ]; then
    step "Updating the existing checkout"
    (cd "$DIR" && git pull -q --ff-only) || warn "could not update the checkout"
  fi

  write_env "$DIR/.env"

  if ! token_ok "$TOKEN"; then
    ok "Installed to $DIR"
    info "Open ${BOLD}$DIR/.env${RESET}, set BOT_TOKEN and ADMIN_ID, then run:"
    info "  ${BOLD}cd $DIR && .venv/bin/python main.py${RESET}"
    return 0
  fi

  step "Installing dependencies (venv)"
  (cd "$DIR" \
    && python3 -m venv .venv \
    && .venv/bin/pip install -q --upgrade pip \
    && .venv/bin/pip install -q -r requirements.txt) || die "dependency installation failed"

  if has ffmpeg; then ok "ffmpeg found"; else
    warn "ffmpeg missing — YouTube/Instagram merging needs it (apt install ffmpeg)"
  fi

  if [ "$NO_START" = "1" ]; then ok "Ready in $DIR (not started, NO_START=1)"; return 0; fi

  step "Starting"
  (cd "$DIR" && nohup .venv/bin/python main.py >> "$DIR/bot.log" 2>&1 & echo $! > "$DIR/bot.pid")
  sleep 3
  if kill -0 "$(cat "$DIR/bot.pid" 2>/dev/null)" 2>/dev/null; then
    ok "Bot is running (pid $(cat "$DIR/bot.pid"))"
  else
    warn "The bot exited — last log lines:"
    tail -n 20 "$DIR/bot.log" >&2 || true
    exit 1
  fi
  info "Logs:   ${BOLD}tail -f $DIR/bot.log${RESET}"
  info "Stop:   ${BOLD}kill \$(cat $DIR/bot.pid)${RESET}"
  info "Update: ${BOLD}cd $DIR && git pull && .venv/bin/pip install -q -r requirements.txt${RESET}"
}

main() {
  printf '\n  %s⚡ Link → File — installer%s\n' "$BOLD$CYAN" "$RESET"

  case "${1:-}" in
    --uninstall)
      if [ -f "$DIR/docker-compose.yml" ]; then (cd "$DIR" && docker compose down) || true; fi
      rm -rf "$DIR"; ok "Removed $DIR (docker volumes kept)"; exit 0 ;;
    -h|--help)
      sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
  esac

  prompt_credentials

  if docker_ready; then
    ok "Docker detected — container install"
    install_docker
  elif has python3 && python3 -c 'import sys; raise SystemExit(0 if sys.version_info[:2] >= (3,10) else 1)'; then
    ok "Docker not available — Python install"
    install_python
  else
    cat >&2 <<'EOF'

  Nothing to install with yet: Docker is not running and Python 3.10+ is missing.

    Docker:   https://docs.docker.com/engine/install/
    Ubuntu:   sudo apt update && sudo apt install -y python3 python3-venv git ffmpeg
    macOS:    brew install python git ffmpeg

  Then run this script again.

EOF
    exit 1
  fi

  printf '\n  %s\n\n' "$([ -n "$TOKEN" ] && echo "Done — open Telegram and send your bot a link." || echo "Finish the .env file, then start the bot.")"
}

main "$@"
